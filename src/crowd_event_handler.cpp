static bool MarkEventSeen(uint32_t eventPtr) {
    for (int i = 0; i < s_seenCount; ++i) if (s_seenEvents[i] == eventPtr) return false;
    if (s_seenCount < 256) { s_seenEvents[s_seenCount++] = eventPtr; return true; }
    // Table full, allow re-fire (slight risk of dupe action, but better than dropping silently)
    return true;
}

static uint32_t ResolveHandle(uint32_t handle) {
    bool trace = (s_resolveTraceLogged < 5);
    if (trace) {
        s_resolveTraceLogged++;
        LOG("  RH: handle=0x%08X  (this is build with world+0x274/0x270 fix)", handle);
    }

    if (handle == 0) { if (trace) LOG("  RH: reject — handle==0"); return 0; }

    uint32_t sentinel = 0;
    if (SafeReadDword((uint32_t)HANDLE_SENTINEL_PTR_ADDR, &sentinel) && handle == sentinel) {
        if (trace) LOG("  RH: reject — handle==sentinel(0x%08X)", sentinel);
        return 0;
    }

    uint32_t low18 = handle & 0x3FFFFu;
    uint32_t index = handle >> 18;             // also slot index AND liveness marker
    if (trace) LOG("  RH: low18=0x%X  index=0x%X (%u)", low18, index, index);
    if (index == 0) { if (trace) LOG("  RH: reject — index==0"); return 0; }

    uint32_t world = 0;
    if (!SafeReadDword((uint32_t)WORLD_SINGLETON_PTR_ADDR, &world)) {
        if (trace) LOG("  RH: reject — cant read *0x00cd7e2c");
        return 0;
    }
    if (trace) LOG("  RH: world=0x%08X", world);
    if (!SafeIsAddrInRange(world)) { if (trace) LOG("  RH: reject — world OOR"); return 0; }

    uint32_t tableOff = (low18 == 1) ? WORLD_DYNAMIC_TABLE_PTR_OFFSET
                                     : WORLD_STATIC_TABLE_PTR_OFFSET;
    uint32_t tablePtr = 0;
    if (!SafeReadDword(world + tableOff, &tablePtr)) {
        if (trace) LOG("  RH: reject — cant read world+0x%X", tableOff);
        return 0;
    }
    if (trace) LOG("  RH: tableOff=0x%X tablePtr=0x%08X", tableOff, tablePtr);
    if (!SafeIsAddrInRange(tablePtr)) { if (trace) LOG("  RH: reject — tablePtr OOR"); return 0; }

    uint32_t slotBase = tablePtr + index * ENTITY_SLOT_STRIDE;
    if (trace) LOG("  RH: slotBase=0x%08X", slotBase);

    uint32_t slotGen = 0;
    if (!SafeReadDword(slotBase + ENTITY_SLOT_GEN_OFFSET, &slotGen)) {
        if (trace) LOG("  RH: reject — cant read slot[0]");
        return 0;
    }
    if (trace) LOG("  RH: slot[0]=0x%X  expect=0x%X", slotGen, index);
    if (slotGen != index) { if (trace) LOG("  RH: reject — liveness mismatch"); return 0; }

    uint32_t entPtr = 0;
    if (!SafeReadDword(slotBase + ENTITY_SLOT_PTR_OFFSET, &entPtr)) {
        if (trace) LOG("  RH: reject — cant read slot[+8]");
        return 0;
    }
    if (trace) LOG("  RH: slot[+8]=0x%08X (entity ptr)", entPtr);
    if (!SafeIsAddrInRange(entPtr)) { if (trace) LOG("  RH: reject — entPtr OOR"); return 0; }
    return entPtr;
}

static void ProcessCrowdEvents(uint32_t mgrAddr) {
    if (!SafeIsAddrInRange(mgrAddr)) return;

    uint32_t queueCount = 0;
    if (!SafeReadDword(mgrAddr + MGR_QUEUE_COUNT_OFFSET, &queueCount)) return;
    if (queueCount == 0 || queueCount > 100) return;

    if (s_queueHadEventsLogged < 10) {
        LOG("ProcessCrowdEvents: mgr=%p queueCount=%u", (void*)mgrAddr, queueCount);
        s_queueHadEventsLogged++;
    }

    uint32_t queueStart = mgrAddr + MGR_QUEUE_BASE_OFFSET;

    for (uint32_t i = 0; i < queueCount; ++i) {
        uint32_t eventPtr = 0;
        if (!SafeReadDword(queueStart + i * 4, &eventPtr)) continue;
        if (eventPtr == 0) continue;

        uint32_t actionCrc = 0;
        if (!SafeReadDword(eventPtr + EVT_ACTION_CRC_OFFSET, &actionCrc)) continue;

        // Diagnostic: log first few action CRCs we see, to confirm what's in
        // the queue and verify our Trigger CRC matches anything that fires.
        if (s_triggerSeenLogged < 30) {
            LOG("  evt[%u]=%p action=0x%08X (Trigger=0x%08X) %s",
                i, (void*)eventPtr, actionCrc, RunCRC::Trigger,
                (actionCrc == RunCRC::Trigger) ? "<- MATCH" : "");
            s_triggerSeenLogged++;
        }

        if (actionCrc != RunCRC::Trigger) continue;

        // Only process events ready to fire (delay <= 0)
        uint32_t delayBits = 0;
        SafeReadDword(eventPtr + EVT_DELAY_OFFSET, &delayBits);
        float delay = *(float*)&delayBits;
        if (delay > 0.0f) continue;

        if (!MarkEventSeen(eventPtr)) continue;

        // Eat the level-load auto-Trigger so crowds boot up visible.
        if (!s_skippedFirstTrigger) {
            s_skippedFirstTrigger = true;
            LOG("  (swallowed level-load auto-Trigger event %p)", (void*)eventPtr);
            continue;
        }

        // DEMO MODE: any Trigger event toggles CrowdItem[0].
        //
        // The proper proxy approach (field-walk to find VespCrowdAction
        // on a custom entity) is blocked: when level.json declares a
        // CrowdProxy with Factory=logic_relay, the engine collapses it
        // into a plain logic_relay at runtime — the extra Vesp* fields
        // exist in the .bin but not on the live entity's class table.
        // Verified by dumping entity+0x00 vtable and entity+0x04 class
        // pointer for all 4 trigger targets: all identical, all generic
        // logic_relay, no per-instance field dictionary.
        //
        // For real per-crowd targeting we'd need either:
        //   (a) a sidecar map keyed by entity GUID/handle, populated by
        //       Vespucci's save flow and read by this DLL at level load
        //   (b) a real C++ subclass registered against the engine's
        //       Factory dispatcher
        // Both are bigger lifts. For today we want a working trigger.
        {
            uint32_t containerPtr = 0;
            if (!SafeReadDword((uint32_t)CROWD_CONTAINER_PTR_ADDR, &containerPtr)) continue;
            if (containerPtr == 0) continue;
            uint32_t itemPtr = 0;
            if (!SafeReadDword(containerPtr + CROWD_CONTAINER_ITEMS_OFFSET, &itemPtr)) continue;
            if (itemPtr == 0) continue;
            if (FindMutationEntry(itemPtr)) ShowCrowdItem(itemPtr);
            else                            HideCrowdItem(itemPtr);
            LOG("DEMO: Trigger event -> toggled CrowdItem[0] (%p)", (void*)itemPtr);
        }
    }
}

// =========================================================================
//  TRAMPOLINE HOOK
// =========================================================================

typedef void (__fastcall *EventQueueProc)(void* manager);
static EventQueueProc s_origCall = NULL;

static void __fastcall HookedProcessEventQueue(void* manager) {
    // Diagnostic: log the first few times our hook actually fires, so we
    // can prove the trampoline JMP is routing the engine's per-frame
    // ProcessEventQueue calls into our DLL.
    if (s_hookFiredLogged < 5) {
        LOG("HOOK FIRED #%d: manager=%p", s_hookFiredLogged, manager);
        s_hookFiredLogged++;
    }
    ProcessCrowdEvents((uint32_t)manager);
    if (s_origCall) s_origCall(manager);
}

static bool InstallEventQueueHook() {
    s_trampolineBuf = VirtualAlloc(NULL, 16, MEM_COMMIT | MEM_RESERVE,
                                   PAGE_EXECUTE_READWRITE);
    if (!s_trampolineBuf) { LOG("VirtualAlloc trampoline failed"); return false; }

    if (!SafeReadBytes(ADDR_PROCESS_EVENT_QUEUE, s_savedBytes, 6)) {
        LOG("read first 6 bytes failed");
        VirtualFree(s_trampolineBuf, 0, MEM_RELEASE);
        s_trampolineBuf = NULL;
        return false;
    }

    // Trampoline = saved 6 bytes + JMP rel32 to (target+6)
    uint8_t* tramp = (uint8_t*)s_trampolineBuf;
    memcpy(tramp, s_savedBytes, 6);
    tramp[6] = 0xE9;
    int32_t rel = (int32_t)((uint32_t)(ADDR_PROCESS_EVENT_QUEUE + 6) - ((uint32_t)tramp + 11));
    memcpy(tramp + 7, &rel, 4);

    s_origCall = (EventQueueProc)s_trampolineBuf;

    DWORD oldProtect = 0;
    if (!VirtualProtect((void*)ADDR_PROCESS_EVENT_QUEUE, 6, PAGE_EXECUTE_READWRITE, &oldProtect)) {
        LOG("VirtualProtect on target failed: %u", (unsigned)GetLastError());
        VirtualFree(s_trampolineBuf, 0, MEM_RELEASE);
        s_trampolineBuf = NULL;
        s_origCall = NULL;
        return false;
    }

    uint8_t* target = (uint8_t*)ADDR_PROCESS_EVENT_QUEUE;
    target[0] = 0xE9;
    int32_t hookRel = (int32_t)((uint32_t)(void*)&HookedProcessEventQueue
                                - (ADDR_PROCESS_EVENT_QUEUE + 5));
    memcpy(target + 1, &hookRel, 4);
    target[5] = 0x90;

    DWORD dummy = 0;
    VirtualProtect((void*)ADDR_PROCESS_EVENT_QUEUE, 6, oldProtect, &dummy);

    LOG("HOOK INSTALLED at FUN_00905838 (trampoline=%p, our_hook=%p)",
        s_trampolineBuf, (void*)&HookedProcessEventQueue);
    return true;
}

static void UninstallEventQueueHook() {
    if (!s_hookInstalled) return;
    DWORD oldProtect = 0;
    if (VirtualProtect((void*)ADDR_PROCESS_EVENT_QUEUE, 6, PAGE_EXECUTE_READWRITE, &oldProtect)) {
        memcpy((void*)ADDR_PROCESS_EVENT_QUEUE, s_savedBytes, 6);
        DWORD dummy = 0;
        VirtualProtect((void*)ADDR_PROCESS_EVENT_QUEUE, 6, oldProtect, &dummy);
    }
    if (s_trampolineBuf) { VirtualFree(s_trampolineBuf, 0, MEM_RELEASE); s_trampolineBuf = NULL; }
    s_origCall = NULL;
    s_hookInstalled = false;
    LOG("HOOK UNINSTALLED");
}

