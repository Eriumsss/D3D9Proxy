extern "C" void CrowdHandler_Init() {
    LOG("CrowdHandler_Init: precomputed CRCs loaded");
    LOG("  VespCrowdAction=0x%08X  VespCrowdTargetMesh=0x%08X  Trigger=0x%08X",
        RunCRC::VespCrowdAction, RunCRC::VespCrowdTargetMesh, RunCRC::Trigger);
}

extern "C" void CrowdHandler_OnFrame() {
    // Install the trampoline hook once on first frame
    if (!s_hookInstalled) {
        if (InstallEventQueueHook()) s_hookInstalled = true;
        else                          s_hookInstalled = true; // don't retry forever
    }

    // F11 manual hide/show fallback. Stays as a debug primitive even
    // while we drive the trigger-driven path forward. If the hook never
    // catches a Trigger event, the user still has a working hide/show
    // they can fall back on. Edge-detected so a held key doesn't strobe.
    bool f11Down = (GetAsyncKeyState(VK_F11) & 0x8000) != 0;
    bool risingEdge = (f11Down && !s_prevF11Down);
    s_prevF11Down = f11Down;
    if (risingEdge) {
        uint32_t containerPtr = 0;
        if (SafeReadDword((uint32_t)CROWD_CONTAINER_PTR_ADDR, &containerPtr) && containerPtr != 0) {
            uint32_t count = 0;
            SafeReadDword(containerPtr + CROWD_CONTAINER_COUNT_OFFSET, &count);
            if (count > 0 && count < 10000) {
                uint32_t itemPtr = 0;
                if (SafeReadDword(containerPtr + CROWD_CONTAINER_ITEMS_OFFSET, &itemPtr)
                    && itemPtr != 0)
                {
                    if (FindMutationEntry(itemPtr)) ShowCrowdItem(itemPtr);
                    else                            HideCrowdItem(itemPtr);
                }
            }
        }
    }
}

extern "C" void CrowdHandler_Shutdown() {
    UninstallEventQueueHook();
    LOG("Restoring %d hidden items", s_mutationCount);
    for (int i = 0; i < s_mutationCount; ++i) {
        SafeWriteDword(s_mutations[i].crowdItemPtr + CROWD_ITEM_INSTNUM_OFFSET,
                       s_mutations[i].originalInstNum);
        SafeWriteDword(s_mutations[i].crowdItemPtr + CROWD_ITEM_ANIMPTR_OFFSET,
                       s_mutations[i].originalAnimPtr);
    }
    s_mutationCount = 0;
    if (s_log) { fclose(s_log); s_log = NULL; }
}
