// =========================================================================
//  crowd_event_handler.cpp — THE REAL EVENT-DRIVEN CROWD HOOK
//
//  F11 dev hotkey is dead. This is the production answer.
//
//  ARCHITECTURE
//  ------------
//  Trampoline-hook FUN_00905838 (ProcessEventQueue). On every per-frame
//  dispatch, we walk the pending queue. For each event where the action
//  CRC matches Trigger AND the target entity has a VespCrowdAction field,
//  we read the entity's VespCrowdTargetMesh value (a CRC), scan the
//  global crowd container at [0x00cd804c] for the matching CrowdItem
//  (mesh CRC stored at item+0x00), and mutate that item's instNum to
//  hide or show its crowd members.
//
//  CRITICAL RULE: WE NEVER CALL ANY ENGINE FUNCTION.
//  --------------------------------------------------
//  The engine uses non-standard ESI/EDI-based calling conventions on
//  FUN_0067e6d8 (hash wrapper) and FUN_007e8bd1 (field lookup). __fastcall
//  casts wrote to junk registers and crashed the game twice. The fix is
//  to do everything ourselves:
//    - CRCs precomputed offline (compute_crowd_crcs.py)
//    - Field-table walked manually (we know the layout)
//    - Crowd container walked manually
//    - Only memory reads + writes. Zero engine ABI dependencies.
//
//  CRC ALGORITHM DISCOVERY
//  -----------------------
//  Pandemic's tools used CRC-32/MPEG-2 (the "runtime" hash, NOT reflected
//  CRC32) for mesh CRCs in 3dCrowd binary. Confirmed by comparing
//  Vespucci's load log against compute_crowd_crcs.py output:
//
//    Item 0 mesh CRC in binary  = 0x1E684210
//    MPEG-2("CRD_CH_urk_spr_idle_01_mesh") = 0x1E684210   <- matches!
//    Reflected(same)            = 0xC2A79148   <- nope
//
//  So we use the RunCRC:: namespace values.
//
//  Authored 2026-05-12.
// =========================================================================

