static uint32_t* const HANDLE_SENTINEL_PTR_ADDR = (uint32_t*)0x00cd82f8;

// Entity-table offsets within the World singleton. Verified against
// FUN_008a3b26 (the canonical handle resolver):
//   handle low 18 bits == 1 -> dynamic table pointer at  *(world + 0x274)
//   handle low 18 bits != 1 -> static  table pointer at  *(world + 0x270)
// Both tables are arrays of 12-byte slots: [generation:4][unused:4][entity_ptr:4].
// generation == (handle >> 18); engine zeros it on slot free, so a stale
// handle dereferences a slot whose [0] no longer matches.
static const uint32_t WORLD_DYNAMIC_TABLE_PTR_OFFSET = 0x274;
static const uint32_t WORLD_STATIC_TABLE_PTR_OFFSET  = 0x270;
static const uint32_t ENTITY_SLOT_STRIDE             = 12;
static const uint32_t ENTITY_SLOT_GEN_OFFSET         = 0x00;
static const uint32_t ENTITY_SLOT_PTR_OFFSET         = 0x08;

// CrowdItem game-side struct (68 bytes).
//
// The retail engine has TWO render paths over the crowd container:
//
//   PATH A: cull → instance render
//     FUN_008c490d (loops container+0x0c[]) → FUN_008c5226 (dispatch)
//       → FUN_008c4a90 (cull, reads +0x04 instNum, writes +0x38 visible_count,
//                       fills vertex buffer, returns AL=(visible>0))
//     If AL==0, FUN_008c5226 early-exits, no per-instance draw.
//     ⇒ Writing 0 to +0x04 disables this path.
//
//   PATH B: anim → batch submit
//     FUN_008c4821 (loops SAME container+0x0c[]) → FUN_008c4e43 per item.
//     FUN_008c4e43 first does `CMP [item+0x18], 0; JZ exit`. If non-zero,
//     it advances anim time, then calls FUN_0088259e which writes a per-frame
//     batch slot and invokes the model's vtable methods at +0x20/+0x24/+0x28
//     (skin/submit/draw). This path IGNORES +0x04 entirely.
//     ⇒ Writing 0 to +0x18 disables this path (early JZ).
//
// To fully hide a CrowdItem in retail, both must be killed simultaneously.
// Save originals to the mutation table for restore.
static const uint32_t CROWD_ITEM_MESHCRC_OFFSET = 0x00;
static const uint32_t CROWD_ITEM_INSTNUM_OFFSET = 0x04;  // Path A kill
static const uint32_t CROWD_ITEM_ANIMPTR_OFFSET = 0x18;  // Path B kill

// Crowd container layout
static const uint32_t CROWD_CONTAINER_ITEMS_OFFSET = 0x0c;
static const uint32_t CROWD_CONTAINER_COUNT_OFFSET = 0x8c;

// Event-manager layout (from FUN_00905838 asm)
static const uint32_t MGR_QUEUE_BASE_OFFSET   = 0x0c;
static const uint32_t MGR_QUEUE_COUNT_OFFSET  = 0x19c;

// Per-event-entry offsets
static const uint32_t EVT_ACTION_CRC_OFFSET = 0x08;
static const uint32_t EVT_TARGET_HND_OFFSET = 0x18;
static const uint32_t EVT_DELAY_OFFSET      = 0x28;

// Entity field-table layout — EXACT, from FUN_007e8bd1 + FUN_007e866b:
//
//   entity_ptr -> [...entity header...]
//                 +0x04: field_table_ptr -> [hdr:4][count:u16][pad:2][unused:4][entries...]
//                                          count at table+0x04 (u16)
//                                          entries start at table+0x0c
//                                          each entry is 0xC bytes:
//                                              [name_CRC:4][type_CRC:4][data_offset:4]
//                 +0x10: field data blob (data_offset is relative to this)
//
// Verified line-by-line:
//   FUN_007e8bd1:007e8bd2  MOV ESI, [EDI+0x4]              ; table ptr at entity+0x04
//   FUN_007e8bd1:007e8bf0  LEA EAX, [EAX + EDI + 0x10]     ; result = entity+0x10+data_off
//   FUN_007e866b:007e8676  MOVZX EBX, word ptr [ESI+0x4]   ; count at table+0x04
//   FUN_007e866b:007e868f  LEA EAX, [EAX*0xc + ESI + 0xc]  ; entries at table+0x0c, stride 12
//   FUN_007e866b:007e8693  CMP [EAX], target_crc           ; entry+0x00 = name_crc
//   FUN_007e866b:007e86cb  MOV EAX, [EAX*0xc + ESI + 0x14] ; entry+0x08 = data_offset
static const uint32_t ENT_FIELD_TABLE_PTR_OFFSET = 0x04;
static const uint32_t ENT_FIELD_DATA_BASE_OFFSET = 0x10;
static const uint32_t TBL_COUNT_OFFSET           = 0x04;
static const uint32_t TBL_ENTRIES_OFFSET         = 0x0C;
static const uint32_t FIELD_ENTRY_STRIDE         = 0x0C;
static const uint32_t ENTRY_NAME_CRC_OFFSET      = 0x00;
static const uint32_t ENTRY_DATA_OFFSET_OFFSET   = 0x08;

