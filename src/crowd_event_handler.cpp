// =========================================================================
//  SAFE MEMORY — VirtualQuery-based, NOT SEH-based.
//
//  The retail game .exe is from 2009, pre-SAFESEH. Our DLL ships with
//  /SAFESEH:YES (MSVC default), which means the OS doesn't recognize our
//  __try/__except handlers as valid in this process and lets page faults
//  bubble up to the unhandled handler. That's what crashed us when an
//  event-queue entry pointed at unmapped memory.
//
//  Fix: query the page state via VirtualQuery BEFORE dereferencing. If
//  the page isn't committed and readable, treat it as a failed read.
//  Slower than SEH but correctness > speed for this hot path.
// =========================================================================

static bool PageIsReadable(uint32_t addr, uint32_t bytes) {
    MEMORY_BASIC_INFORMATION mbi;
    memset(&mbi, 0, sizeof(mbi));
    if (VirtualQuery((LPCVOID)addr, &mbi, sizeof(mbi)) == 0) return false;
    if (mbi.State != MEM_COMMIT) return false;
    DWORD bad = PAGE_NOACCESS | PAGE_GUARD;
    if (mbi.Protect & bad) return false;
    // Check that the read doesn't span past the end of this committed region
    uint32_t regionBase = (uint32_t)mbi.BaseAddress;
    uint32_t regionEnd  = regionBase + (uint32_t)mbi.RegionSize;
    if (addr + bytes > regionEnd) {
        // Might still be readable if the next region is also committed;
        // for simplicity be conservative and reject. Most game data
        // structs are tiny and fit inside one region.
        return false;
    }
    return true;
}

static bool SafeReadDword(uint32_t addr, uint32_t* out) {
    if (!PageIsReadable(addr, 4)) return false;
    *out = *(volatile uint32_t*)addr;
    return true;
}
static bool SafeWriteDword(uint32_t addr, uint32_t val) {
    if (!PageIsReadable(addr, 4)) return false;
    MEMORY_BASIC_INFORMATION mbi;
    memset(&mbi, 0, sizeof(mbi));
    if (VirtualQuery((LPCVOID)addr, &mbi, sizeof(mbi)) == 0) return false;
    // Must be writable
    DWORD writable_mask = PAGE_READWRITE | PAGE_WRITECOPY |
                          PAGE_EXECUTE_READWRITE | PAGE_EXECUTE_WRITECOPY;
    if ((mbi.Protect & writable_mask) == 0) return false;
    *(volatile uint32_t*)addr = val;
    return true;
}
static bool SafeReadBytes(uint32_t addr, void* dst, uint32_t n) {
    if (!PageIsReadable(addr, n)) return false;
    memcpy(dst, (const void*)addr, n);
    return true;
}
static bool SafeReadWord(uint32_t addr, uint16_t* out) {
    if (!PageIsReadable(addr, 2)) return false;
    *out = *(volatile uint16_t*)addr;
    return true;
}
static bool SafeIsAddrInRange(uint32_t addr) {
    return addr >= 0x00010000 && addr < 0x80000000;
}

// =========================================================================
//  ENTITY FIELD-TABLE WALK (no engine function calls)
//
//  Returns a pointer to the field's value bytes within the entity, or 0
//  if the field name CRC isn't present in this entity's table.
//
//  Layout assumption (from FUN_007e8bd1 + FUN_007e866b asm):
//    [entity + 0x04] = field_table_ptr
//    The table starts with header bytes, then [count:u16] at some
//    offset, then entries at table+offset+4 (4-aligned after count u16),
//    each entry being 0xC bytes [name_CRC, type_CRC, data_offset].
//
//  Robust implementation: try several candidate header sizes and pick
//  whichever produces a sane count (< 1000) AND whose first entry's
//  name_CRC is non-zero. If nothing looks sane, return 0 (treat as
//  "field not found"). Better to false-negative than crash.
// =========================================================================

static int s_fieldDumpLogged = 0;

static uint32_t WalkEntityFieldTable(uint32_t entity_addr, uint32_t target_name_crc)
{
    bool dump = (s_fieldDumpLogged < 4);
    if (dump) s_fieldDumpLogged++;

    if (!SafeIsAddrInRange(entity_addr)) {
        if (dump) LOG("  FW: entity 0x%08X OOR", entity_addr);
        return 0;
    }

    // Dump entity header (first 32 bytes) so we can see what's there.
    if (dump) {
        uint32_t hdr[8] = {0};
        for (int i = 0; i < 8; ++i) SafeReadDword(entity_addr + i*4, &hdr[i]);
        LOG("  FW: entity=0x%08X hdr: +0=0x%08X +4=0x%08X +8=0x%08X +c=0x%08X",
            entity_addr, hdr[0], hdr[1], hdr[2], hdr[3]);
        LOG("           +10=0x%08X +14=0x%08X +18=0x%08X +1c=0x%08X",
            hdr[4], hdr[5], hdr[6], hdr[7]);
    }

    uint32_t table_addr = 0;
    if (!SafeReadDword(entity_addr + ENT_FIELD_TABLE_PTR_OFFSET, &table_addr)) {
        if (dump) LOG("  FW: cant read entity+0x04");
        return 0;
    }
    if (dump) LOG("  FW: table_addr=0x%08X", table_addr);
    if (!SafeIsAddrInRange(table_addr)) {
        if (dump) LOG("  FW: table_addr OOR");
        return 0;
    }

    // Dump table header (first 24 bytes)
    if (dump) {
        uint32_t th[6] = {0};
        for (int i = 0; i < 6; ++i) SafeReadDword(table_addr + i*4, &th[i]);
        LOG("  FW: table hdr: +0=0x%08X +4=0x%08X +8=0x%08X +c=0x%08X +10=0x%08X +14=0x%08X",
            th[0], th[1], th[2], th[3], th[4], th[5]);
    }

    uint16_t count = 0;
    if (!SafeReadWord(table_addr + TBL_COUNT_OFFSET, &count)) {
        if (dump) LOG("  FW: cant read count at table+0x04");
        return 0;
    }
    if (dump) LOG("  FW: count=%u (looking for 0x%08X)", count, target_name_crc);
    if (count == 0 || count > 1000) {
        if (dump) LOG("  FW: count out of range");
        return 0;
    }

    if (dump) {
        uint32_t maxDump = (count < 16) ? count : 16;
        for (uint32_t i = 0; i < maxDump; ++i) {
            uint32_t ea = table_addr + TBL_ENTRIES_OFFSET + i * FIELD_ENTRY_STRIDE;
            uint32_t name = 0, type = 0, off = 0;
            SafeReadDword(ea + 0, &name);
            SafeReadDword(ea + 4, &type);
            SafeReadDword(ea + 8, &off);
            LOG("    [%u] name=0x%08X type=0x%08X off=0x%X", i, name, type, off);
        }
    }

    for (uint32_t i = 0; i < count; ++i) {
        uint32_t entry_addr = table_addr + TBL_ENTRIES_OFFSET + i * FIELD_ENTRY_STRIDE;
        uint32_t name_crc = 0;
        if (!SafeReadDword(entry_addr + ENTRY_NAME_CRC_OFFSET, &name_crc)) break;
        if (name_crc == target_name_crc) {
            uint32_t data_off = 0;
            if (!SafeReadDword(entry_addr + ENTRY_DATA_OFFSET_OFFSET, &data_off)) return 0;
            return entity_addr + ENT_FIELD_DATA_BASE_OFFSET + data_off;
        }
    }
    return 0;
}

// =========================================================================
//  CROWD CONTAINER WALK
// =========================================================================

static uint32_t FindCrowdItemByMeshCrc(uint32_t target_mesh_crc) {
    uint32_t containerPtr = 0;
    if (!SafeReadDword((uint32_t)CROWD_CONTAINER_PTR_ADDR, &containerPtr)) return 0;
    if (containerPtr == 0) return 0;

    uint32_t count = 0;
    if (!SafeReadDword(containerPtr + CROWD_CONTAINER_COUNT_OFFSET, &count)) return 0;
    if (count == 0 || count > 10000) return 0;

    for (uint32_t i = 0; i < count; ++i) {
        uint32_t itemPtr = 0;
        if (!SafeReadDword(containerPtr + CROWD_CONTAINER_ITEMS_OFFSET + i * 4, &itemPtr)) continue;
        if (itemPtr == 0) continue;

        uint32_t mesh_crc = 0;
        if (!SafeReadDword(itemPtr + CROWD_ITEM_MESHCRC_OFFSET, &mesh_crc)) continue;
        if (mesh_crc == target_mesh_crc) return itemPtr;
    }
    return 0;
}

// =========================================================================
//  HIDE / SHOW
// =========================================================================

static CrowdMutationEntry* FindMutationEntry(uint32_t itemPtr) {
    for (int i = 0; i < s_mutationCount; ++i)
        if (s_mutations[i].crowdItemPtr == itemPtr) return &s_mutations[i];
    return NULL;
}

static void HideCrowdItem(uint32_t itemPtr) {
    if (!itemPtr) return;
    if (FindMutationEntry(itemPtr)) { LOG("Hide: %p already hidden", (void*)itemPtr); return; }
    uint32_t origInst = 0, origAnim = 0;
    if (!SafeReadDword(itemPtr + CROWD_ITEM_INSTNUM_OFFSET, &origInst)) return;
    if (!SafeReadDword(itemPtr + CROWD_ITEM_ANIMPTR_OFFSET, &origAnim)) return;
    if (s_mutationCount >= 64) { LOG("Hide: mutation table full"); return; }
    s_mutations[s_mutationCount].crowdItemPtr    = itemPtr;
    s_mutations[s_mutationCount].originalInstNum = origInst;
    s_mutations[s_mutationCount].originalAnimPtr = origAnim;
    s_mutationCount++;
    // Path A kill — must succeed or we bail without registering.
    if (!SafeWriteDword(itemPtr + CROWD_ITEM_INSTNUM_OFFSET, 0)) { s_mutationCount--; return; }
    // Path B kill — restore +0x04 if this fails so we leave no half-state.
    if (!SafeWriteDword(itemPtr + CROWD_ITEM_ANIMPTR_OFFSET, 0)) {
        SafeWriteDword(itemPtr + CROWD_ITEM_INSTNUM_OFFSET, origInst);
        s_mutationCount--;
        return;
    }
    LOG("Hide: item %p instNum %u->0  animPtr 0x%08X->0", (void*)itemPtr, origInst, origAnim);
}

static void ShowCrowdItem(uint32_t itemPtr) {
    if (!itemPtr) return;
    CrowdMutationEntry* e = FindMutationEntry(itemPtr);
    if (!e) { LOG("Show: %p not in mutation table", (void*)itemPtr); return; }
    SafeWriteDword(itemPtr + CROWD_ITEM_INSTNUM_OFFSET, e->originalInstNum);
    SafeWriteDword(itemPtr + CROWD_ITEM_ANIMPTR_OFFSET, e->originalAnimPtr);
    LOG("Show: item %p instNum->%u  animPtr->0x%08X",
        (void*)itemPtr, e->originalInstNum, e->originalAnimPtr);
    int slot = (int)(e - s_mutations);
    s_mutations[slot] = s_mutations[s_mutationCount - 1];
    s_mutationCount--;
}

